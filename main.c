#include <stdio.h>
#include <math.h>

int main() {
    // 1. Оголошення та ініціалізація змінних
    double x = 0, y = 0;
    double x1 = 0, x2 = 0, x3 = 0;

    // Змінні для збереження результатів
    double res1 = 0, res2 = 0, res3 = 0, res4 = 0, res5 = 0;

    // 2. Введення початкових даних на початку програми
    printf("Введіть x: ");
    scanf("%lf", &x);

    printf("Введіть y: ");
    scanf("%lf", &y);

    printf("Введіть x1, x2, x3: ");
    scanf("%lf %lf %lf", &x1, &x2, &x3);

    printf("\n--- Результати обчислень ---\n");

    // Завдання 1 (Варіант 3)
    if (y == -1 || x == -34) {
        printf("Завдання 1: Помилка ОДЗ (ділення на нуль)\n");
    } else {
        res1 = (x + y) / (y + 1) - (x * y - 12) / (34 + x);
        printf("Завдання 1: res1 = %.4f\n", res1);
    }

    // Завдання 2 (Варіант 10)
    if (x == 0) {
        printf("Завдання 2: Помилка ОДЗ (x = 0)\n");
    } else {
        res2 = pow(1 + 1 / (x * x), x) - 12 * x * x * y;
        printf("Завдання 2: res2 = %.4f\n", res2);
    }

    // Завдання 3 (Варіант 29)
    if (x == 0) {
        printf("Завдання 3: Помилка ОДЗ (x = 0)\n");
    } else {
        res3 = (x1 * x2 + x1 * x3 + x2 * x3) / x;
        printf("Завдання 3: res3 = %.4f\n", res3);
    }

    // Завдання 4 (Варіант 6)
    if (x < 1) {
        printf("Завдання 4: Помилка ОДЗ (вираз під коренем < 0)\n");
    } else {
        res4 = sin(sqrt(x + 1)) - sin(sqrt(x - 1));
        printf("Завдання 4: res4 = %.4f\n", res4);
    }

    // Завдання 5 (Варіант 7)
    if (1 - tan(x) <= 0 || cos(x) == 0 || sin(x) == 0) {
        printf("Завдання 5: Помилка ОДЗ (від'ємна основа або неіснуючий tg/ctg)\n");
    } else {
        res5 = pow(1 - tan(x), 1 / tan(x)) + cos(x - y);
        printf("Завдання 5: res5 = %.4f\n", res5);
    }

    return 0;
}